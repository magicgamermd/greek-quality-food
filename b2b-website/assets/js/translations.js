// Current language state
let currentLang = localStorage.getItem('gf_lang') || 'bg';

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('gf_lang', lang);
  applyTranslations();
  updateLangButtons();
}

function t(key) {
  return translations[currentLang][key] || translations['bg'][key] || key;
}

function applyTranslations() {
  document.querySelectorAll('[data-t]').forEach(el => {
    const key = el.getAttribute('data-t');
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-t-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-t-placeholder'));
  });
  document.querySelectorAll('[data-t-title]').forEach(el => {
    el.title = t(el.getAttribute('data-t-title'));
  });
  document.querySelectorAll('[data-t-value]').forEach(el => {
    el.value = t(el.getAttribute('data-t-value'));
  });
}

function updateLangButtons() {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
}

// Auth helpers
function isLoggedIn() {
  return localStorage.getItem('gf_logged_in') === 'true';
}

function getUser() {
  return JSON.parse(localStorage.getItem('gf_user') || '{"name":"Партньор","company":""}');
}

function logout() {
  localStorage.removeItem('gf_logged_in');
  localStorage.removeItem('gf_user');
  window.location.href = 'login.html';
}

// Cart helpers
function getCart() {
  return JSON.parse(localStorage.getItem('gf_cart') || '[]');
}

function saveCart(cart) {
  localStorage.setItem('gf_cart', JSON.stringify(cart));
  updateCartBadge();
}

function updateCartBadge() {
  const cart = getCart();
  const count = cart.reduce((sum, item) => sum + item.qty, 0);
  document.querySelectorAll('.cart-badge').forEach(el => {
    el.textContent = count;
    el.style.display = count > 0 ? 'flex' : 'none';
  });
}

// Init on DOM ready
document.addEventListener('DOMContentLoaded', () => {
  applyTranslations();
  updateLangButtons();
  updateCartBadge();

  // Update nav based on login state
  const loginNavItem = document.getElementById('nav-login-item');
  const portalNavItem = document.getElementById('nav-portal-item');
  const logoutBtn = document.getElementById('nav-logout-btn');

  if (isLoggedIn()) {
    if (loginNavItem) loginNavItem.style.display = 'none';
    if (portalNavItem) portalNavItem.style.display = 'block';
    if (logoutBtn) logoutBtn.style.display = 'block';
  } else {
    if (loginNavItem) loginNavItem.style.display = 'block';
    if (portalNavItem) portalNavItem.style.display = 'none';
    if (logoutBtn) logoutBtn.style.display = 'none';
  }
});
