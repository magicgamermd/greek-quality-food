// Служебните партидни номера са складова идентичност, не въведен от
// човек номер, и НЕ се показват на печатни документи:
//   - "АВТО-{доставка}-{ред}"  — авто-партида при доставка без номер
//   - "НАЧАЛНО"                — откриваща партида (back-order изписване)
// Срокът на годност на партидата се показва нормално — той е реално
// въведен от склада. Вътрешно (Склад, FEFO, одит) номерата се виждат.
export function displayBatchNumber(value?: string | null): string | null {
  const v = (value ?? "").trim();
  if (!v) return null;
  if (v.startsWith("АВТО-")) return null;
  if (v === "НАЧАЛНО") return null;
  return v;
}
