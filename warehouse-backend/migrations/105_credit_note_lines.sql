-- Редовете на кредитното известие по продажба, както са издадени.
--
-- Досега редовете не се пазеха никъде — копие, английски вариант или
-- изгубен файл ги възстановяваше от ВСИЧКИ редове на поръчката. За цяло
-- КИ това съвпада, за частично — не: документът излизаше с редове, които
-- не са кредитирани. Сега при издаване се записва точно това, което е
-- отпечатано (кол., цена, отстъпка, стойност), и всяко преизчертаване
-- ползва него.
--
-- NULL за стари кредитни известия (издадени преди колоната) — за тях
-- остава възстановяването от поръчката.
ALTER TABLE invoices
  ADD COLUMN IF NOT EXISTS credit_note_lines JSONB;

COMMENT ON COLUMN invoices.credit_note_lines IS
  'Отпечатаните редове на кредитно известие (JSON масив) — източник за копия и EN вариант';
