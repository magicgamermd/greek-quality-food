-- Избрано от склада разпределение на ред по партиди (срокове на годност).
--
-- Досега партидите на неизпълнена поръчка ги избираше програмата при
-- изпълнение — най-старата първо (FEFO). Складът обаче дава физически
-- конкретни партиди: за веригите (Фантастико) по-дълъг срок, а понякога
-- един ред от две партиди — напр. 5 кг с годност 15.12 + 5 кг с 08.12.
-- Поръчка №363 (17.10.2026) показа разминаването: програмата изписа
-- 00081026 (08.12), а реално беше дадена 00151226 (15.12) и партидата
-- беше дописана на ръка върху търговския документ.
--
-- batch_plan = [{"batch_id": 1350, "quantity": 5}, {"batch_id": 1303, "quantity": 5}]
--   • сумата на quantity = количеството на реда;
--   • при изпълнение се изписва ТОЧНО това (наличност и срок се проверяват
--     тогава), вместо автоматичния избор;
--   • търговският документ и стоковата разписка го печатат още преди
--     изпълнението — по ред за всяка партида.
-- NULL = както досега (ръчно избрана една партида или автоматично FEFO).
ALTER TABLE order_items
  ADD COLUMN IF NOT EXISTS batch_plan JSONB;

ALTER TABLE order_items
  DROP CONSTRAINT IF EXISTS chk_order_items_batch_plan_array;
ALTER TABLE order_items
  ADD CONSTRAINT chk_order_items_batch_plan_array
  CHECK (batch_plan IS NULL OR jsonb_typeof(batch_plan) = 'array');

COMMENT ON COLUMN order_items.batch_plan IS
  'Избрано разпределение по партиди [{batch_id, quantity}]; NULL = автоматично (FEFO) или order_items.batch_id';
