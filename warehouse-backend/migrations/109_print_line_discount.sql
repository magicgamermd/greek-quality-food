-- Колона „Т.О. %“ (отстъпка на ред) на печатните документи
-- (искане по образец на Microinvest, 04.11.2026: „отстъпката да
-- присъства навсякъде“; magic: „на всички нови документи“).
--
-- От май 2026 (MERT-M) документите печатат само цената след отстъпката.
-- Вече ИЗДАДЕНИТЕ документи не бива да се променят (чл. 116 ЗДДС), а
-- сървърът няма постоянен диск за PDF-ите и след всеки деплой ги чертае
-- наново от данните — затова всеки документ носи как е издаден (както
-- unit_price_rule от мигр. 106):
--   false — без колона (всички съществуващи; подразбиране)
--   true  — с колона „Т.О. %“, когато поне един ред има отстъпка
--           (новите; кодът го задава при създаване)
--
-- Подразбирането е СТАРОТО поведение: документ, създаден от стария код
-- между миграцията и деплоя, остава както е издаден.
--   • invoices — фактура, проформа, кредитно известие;
--   • orders   — стокова разписка, оферта, протокол (чертаят се от поръчката).
ALTER TABLE invoices
  ADD COLUMN IF NOT EXISTS print_line_discount BOOLEAN NOT NULL DEFAULT false;

ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS print_line_discount BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN invoices.print_line_discount IS
  'Печат с колона „Т.О. %“ (издадени след 04.11.2026); false = само цената след отстъпката';
COMMENT ON COLUMN orders.print_line_discount IS
  'Документите на поръчката (стокова разписка, оферта, протокол) с колона „Т.О. %“';
