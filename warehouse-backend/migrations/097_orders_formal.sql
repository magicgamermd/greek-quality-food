-- 093_orders_formal.sql
-- Формална поръчка/фактура (документална, без складово движение).
--
-- МЕРТ-М понякога продава бройки, които НИКОГА не са заведени в склада
-- (не са в inventory). За такава продажба трябва нормална фактура, но
-- няма складова стока за изваждане. Намаляване би създало фантомен
-- минус в наличността.
--
-- formal=true → поръчката се държи като нормална във ВСИЧКО (пореден
-- номер, ДДС, плащане, дневен оборот, status flow), ЕДИНСТВЕНО НЕ пипа
-- складовата наличност: прескача проверката за наличност при създаване,
-- deductProductStock при fulfill и stock restore при отказ/редакция.
-- Огледало на поведението на quoted поръчките.
--
-- Additive, backward-compatible: стари редове = false = нормални поръчки.

ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS formal BOOLEAN NOT NULL DEFAULT false;
