-- 086_orders_goods_taken_unpaid.sql
-- Flag за поръчки тип "взе стоката, ще плати по-късно" (отложено плащане).
-- Клиент взема стоката физически, но не плаща в момента — ще се върне
-- след 2-3 дни да плати в брой или с карта. Често е при познати клиенти,
-- физически лица които забравят кеша, или ситуации с малки суми.
--
-- ВАЖНО за дневния отчет (логика per касиерка brief 2026-05-22):
--   • При създаване (ден N): сумата ВЛИЗА в "Общ оборот" на ден N,
--     но НЕ В "В брой" / "ПОС" / "По банка" — защото пари не са дошли.
--   • При плащане (ден N+3): плащането ВЛИЗА в "В брой" (или "ПОС") KPI
--     на ден N+3, но НЕ В "Общ оборот" на N+3 — за да не се дублира.
--
-- Без този флаг такива поръчки изглеждат като обикновени "Неплатени днес"
-- и системата не различава между "забавено плащане" и "истински дълг".
-- В дневния отчет такива редове ще се показват с маркер "Взе/неплат."
-- вместо "Неплатена".

BEGIN;

ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS goods_taken_unpaid BOOLEAN NOT NULL DEFAULT FALSE;

-- Index за бърз look-up в дневния отчет — обикновено малък брой такива
-- поръчки на ден, така че partial index по TRUE стойностите е достатъчен.
CREATE INDEX IF NOT EXISTS idx_orders_goods_taken_unpaid
  ON orders (order_date)
  WHERE goods_taken_unpaid = TRUE;

COMMIT;
